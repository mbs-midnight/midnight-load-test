class RateGovernor {
  private tokens: number;
  private last = Date.now();
  constructor(private ratePerSec: number, private burst: number) { this.tokens = burst; }
  async take(): Promise<void> {
    if (this.ratePerSec <= 0) return;
    for (;;) {
      const now = Date.now();
      this.tokens = Math.min(this.burst, this.tokens + ((now - this.last) / 1000) * this.ratePerSec);
      this.last = now;
      if (this.tokens >= 1) { this.tokens -= 1; return; }
      await sleep(Math.max(5, (1 - this.tokens) / this.ratePerSec * 1000));
    }
  }
}

/**
 * One state snapshot.
 *
 * The old implementation called sub.unsubscribe() from INSIDE the subscribe
 * callback. If the observable emits synchronously on subscribe, `sub` is still
 * in its temporal dead zone there, the ReferenceError is swallowed by an empty
 * catch, and the subscription LEAKS -- thousands of live subscriptions over a
 * long run. Assigning the handle first and unsubscribing on the next microtask
 * makes the teardown reachable in both the sync and async emission cases.
 */
function snapshot(wallet: any, timeoutMs = 15_000): Promise<any> {
  return new Promise((resolve) => {
    let sub: any;
    let done = false;
    const finish = (s: any) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      resolve(s);
      queueMicrotask(() => { try { sub?.unsubscribe?.(); } catch { /* ignore */ } });
    };
    // A dead wallet's state() may never emit. Without a timeout the lane awaits
    // forever and the run looks idle rather than broken -- which is exactly how
    // the 403-killed wallets presented. Resolving null lets the caller treat
    // "no state" as "dead" and rebuild.
    const timer = setTimeout(() => finish(null), timeoutMs);
    try {
      sub = wallet.state().subscribe(finish);
    } catch {
      finish(null);
    }
  });
}

/**
 * Is this wallet's sync dead?
 *
 * The failure this guards against: wallet-sdk-indexer-client builds its GraphQL
 * WebSocket with `shouldRetry: () => false`, so ONE refused connect is permanent.
 * The wallet then sits at isConnected=false forever and raises nothing. Observed
 * for real -- a transient `Forbidden` from the indexer took two wallets to zero
 * throughput for the remaining six minutes of a run, silently. From the outside
 * a throttled wallet and an idle chain look identical, which makes any long run
 * untrustworthy without this check.
 */
function syncLooksBroken(st: any): boolean {
  if (!st) return true;                       // no state at all (timed out)
  const u = st?.unshielded?.progress;
  const d = st?.dust?.progress;
  if (!u || !d) return true;
  return !(Boolean(u.isConnected) && Boolean(d.isConnected));
}

