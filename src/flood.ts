/**
 * Bound an SDK call that has no timeout of its own.
 *
 * The SDK's prove and submit calls can park forever: a 240s churn was observed
 * still alive after 31 minutes with one lane stuck inside an await. The hard
 * stop guarantees the PROCESS ends, but not that the RUN keeps its strength --
 * the watchdog cannot rescue a lane blocked inside an await (it rebuilds the
 * wallet while the lane still holds the old call), so a hung lane is lost for
 * the remainder of the run and throughput silently erodes.
 *
 * Timeouts are deliberately NOT retried. A submit that timed out may still have
 * reached the chain, and while a rebuild cannot double-spend (the coins are
 * already spent on-chain, so the node simply rejects it) it would burn a proof
 * to learn that. Freeing the lane is the win; the next iteration proceeds
 * normally, and landings are confirmed from the indexer regardless.
 */
class StageTimeout extends Error {}

async function withTimeout<T>(p: Promise<T>, ms: number, what: string): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    return await Promise.race([
      p,
      new Promise<never>((_, reject) => {
        timer = setTimeout(() => reject(new StageTimeout(`stage '${what}' exceeded ${ms}ms`)), ms);
      }),
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}

