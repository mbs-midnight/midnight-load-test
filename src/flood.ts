/**
 * flood.ts -- fill BLOCKS on Midnight with cheap unshielded NIGHT transfers.
 *
 * WHAT CHANGED AND WHY (read this before running anything)
 * -------------------------------------------------------
 * The previous version never successfully submitted a single transaction. Three
 * of its founding assumptions were wrong, all verified against the installed SDK:
 *
 *  1. EVERY OUTPUT NEEDS A TOKEN TYPE. wallet-sdk-facade's
 *       interface TokenTransfer { type: RawTokenType; receiverAddress; amount }
 *     makes `type` mandatory. The old code set it only on the WRAPPER
 *     ({type:'unshielded', outputs}) and never on the outputs, then hid the
 *     resulting compile error behind `as any`. The balancer filters candidate
 *     coins with `coin.type === tokenType`, matched nothing against `undefined`,
 *     and threw -- surfacing as the bare string "Insufficient funds" in
 *     split.jsonl. No choice of --split-into/--coin-star could ever have fixed it.
 *
 *  2. UNSHIELDED TRANSFERS ARE NOT PROOF-FREE. finalizeRecipe -> facade
 *     finalizeTransaction -> `this.provingService.prove(tx)`. The DUST fee spend
 *     is a DustSpend<PreProof> and must be proven. It is a small fixed circuit,
 *     nothing like k=18, but the proof server IS in the hot path of every tx.
 *
 *  3. ONE DUST COIN = ONE IN-FLIGHT FEE-PAYING TX. dust-wallet's
 *     availableDustTokens() filters out every coin whose nonce is in pendingDust,
 *     and the successor coin cannot be built locally -- it needs a chain-assigned
 *     commitment index delivered by the dustSpendProcessed event on sync. So a
 *     wallet holding ONE dust coin is pinned to one fee-paying transaction per
 *     inclusion+sync round trip (~1 per 6s block), no matter how fast proving or
 *     node ingest are. THIS, not proving, is the throughput ceiling.
 *
 * NOTE (measured after the fact): the engine/ammo separation described below
 * turned out to be UNNECESSARY. Dust registration is bound to the night KEY, not
 * to a single UTXO, so every output of a split inherits registration and keeps
 * generating dust. Splitting into N coins simply yields N dust coins -- i.e. N
 * concurrent lanes -- with nothing to protect. The text is kept because the
 * SIZING logic still holds; only the protection rationale is obsolete.
 *
 * THE ENGINE / AMMO MODEL (superseded -- see note above)
 * -----------------------
 * DUST is generated by REGISTERED NIGHT UTXOs, and spending a registered UTXO
 * stops its generator (a dtime is set and the dust decays over
 * dustGracePeriodSeconds = 3h). So the two roles must never be mixed:
 *
 *   ENGINE coins -- registered, LARGE, never spent. Each one is an independent
 *                   dust coin, so ENGINE COUNT = MAX CONCURRENT IN-FLIGHT TXS
 *                   for that wallet. This is the throughput dial.
 *   AMMO coins   -- unregistered, SMALL, spent freely by the churn loop.
 *
 * They are told apart by meta.registeredForDustGeneration -- the chain's own
 * flag, not local bookkeeping, so it survives restarts.
 *
 * WHY ENGINES ARE LARGE AND AMMO IS SMALL: the balancer's chooseCoin sorts
 * candidates ASCENDING and takes the smallest that matches. Making every engine
 * bigger than every ammo coin means the balancer consumes ammo first and only
 * reaches an engine if ammo is exhausted -- the separation is enforced by coin
 * size, not by hope. The churn loop additionally refuses to build a transfer it
 * cannot cover from ammo alone, so an engine is never silently eaten.
 *
 * PHASES
 *   --phase deregister OPTIONAL. Releases a NIGHT UTXO from dust generation.
 *                     NOT required before spending -- that was a wrong guess;
 *                     error 192 turned out to be a missing signature, not a
 *                     registration conflict. Kept because deliberately retiring
 *                     an engine is still a thing you may want to do.
 *   --phase split     one self-transfer per wallet: the funded UTXO -> E large
 *                     engine outputs + A small ammo outputs.
 *   --phase register  register the E largest unregistered native UTXOs for DUST
 *                     generation. Run AFTER split confirms. Idempotent.
 *   --phase churn     THE LOAD GENERATOR. Repeated N-output SELF-transfers using
 *                     ammo only. Self-transfer means ammo is never depleted and
 *                     no wallet starves, unlike the old round-robin drain.
 *                     --lanes N runs N concurrent workers per wallet, which is
 *                     how you actually steer block fullness. NOTE: --outputs is
 *                     NOT a useful dial -- measured on chain, a 32-output
 *                     transfer is 3,851 B against a 3,816 B two-output baseline,
 *                     i.e. ~1.2 B per extra output. Transfer size is dominated by
 *                     the fixed DUST spend proof, so bytes/sec is governed by
 *                     TRANSACTIONS IN FLIGHT, not by transaction size.
 *   --phase flood     legacy 1-output round-robin/sink transfers, bug-fixed.
 *                     Kept for comparison; churn is strictly better for fullness.
 *
 * MEASURED SIZING INPUTS (preview, from midnight_dust_probe.py):
 *   block cadence 6.000s | block_usage limit 200,000 B (protocol constant)
 *   1-output transfer ~673 B | transfer with change ~3,816 B | k=18/19 call ~8,151 B
 *   => 50% fullness = 100,000 B/block = ~26 change-carrying transfers/block
 *      = ~4.4 tx/s sustained.
 */
