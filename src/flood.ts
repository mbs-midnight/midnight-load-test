/**
 * Submit with a configurable wait, bypassing the facade when asked.
 *
 * WHY: facade.submitTransaction hardcodes `submissionService.submitTransaction(tx,
 * 'Finalized')`. Measured, that wait is ~19s of a ~23s cycle -- we sit through
 * several blocks of finality for a load generator that does not care. And because
 * a wallet sustains exactly ONE in-flight transaction (verified: w001 has 33 dust
 * coins and still managed one at a time; two WALLETS ran genuinely in parallel at
 * 93% concurrency), that wait IS the per-wallet cycle time. Shortening it is the
 * only lever that makes 50% fullness reachable with 15 wallets instead of ~100.
 *
 * The underlying service accepts 'Submitted' | 'InBlock' | 'Finalized'; only the
 * facade's public method is fixed. So we replicate its body -- register the
 * pending transaction, submit, return the identifier, revert on failure -- with
 * the wait we want. Both fields are ordinary properties on the facade, but if a
 * future version makes them private this falls back to the public method rather
 * than breaking.
 *
 * TRADE-OFF: with 'Submitted' the node has ACCEPTED the transaction but we have
 * not seen it in a block. Our submit count is therefore no longer proof of
 * inclusion -- landing must be confirmed from the indexer afterwards. That is
 * already how the measurement works (the generator never computes a fee), so it
 * costs nothing analytically, but never quote submit counts as landed counts.
 */
type SubmitWait = 'Submitted' | 'InBlock' | 'Finalized';

async function submitWithWait(wallet: any, finalized: any, wait: SubmitWait): Promise<string> {
  if (wait === 'Finalized') return await wallet.submitTransaction(finalized);
  const svc = wallet?.submissionService;
  const pending = wallet?.pendingTransactionsService;
  if (typeof svc?.submitTransaction !== 'function') {
    // Fast path unavailable -- do not silently change semantics, just be slow.
    return await wallet.submitTransaction(finalized);
  }
  try {
    await pending?.addPendingTransaction?.(finalized);
    await svc.submitTransaction(finalized, wait);
    return finalized.identifiers().at(-1);
  } catch (e) {
    // Mirror the facade: release the claimed UTXOs/dust so the lane is not stuck.
    try { await wallet.revert?.(finalized); } catch { /* best effort */ }
    throw e;
  }
}


/**
 * Stop wallets, but never let shutdown hang the process.
 *
 * OBSERVED: two runs were still alive 17 and 19 HOURS after finishing, holding
 * 16 established indexer connections between them. Cause: the final
 * `await Promise.allSettled(started.map(w => w.stop?.()))` never settles, so
 * main() never resolves and the `process.exit(0)` after it never runs. deploy.ts
 * documents the same hang.
 *
 * This is not just untidy. Those zombies keep syncing wallets against the
 * indexer indefinitely, which very plausibly contributed to the rate limiting we
 * had attributed purely to submission rate. Bound the wait, then leave; the
 * caller force-exits.
 */
async function shutdown(wallets: any[]): Promise<void> {
  const stops = wallets.map((w) => {
    try { return Promise.resolve(w?.stop?.()); } catch { return Promise.resolve(); }
  });
  await Promise.race([Promise.allSettled(stops), sleep(15_000)]);
}

interface StageBudgets { buildMs: number; proveMs: number; submitMs: number }

async function submitTransfer(
  bundle: any, outputs: { type: string; receiverAddress: any; amount: bigint }[],
  wait: SubmitWait = 'Finalized',
  budgets: StageBudgets = { buildMs: 120_000, proveMs: 300_000, submitMs: 180_000 },
): Promise<{ txId: string; buildMs: number; proveMs: number; submitMs: number }> {
  // Stage the timers so a slow run can be attributed. finalizeRecipe is the
  // proof-server round trip (facade -> provingService.prove); separating it from
  // build and submit is the only way to tell whether the ceiling is the prover,
  // the node, or dust availability.
  const t0 = Date.now();
  const recipe = await withTimeout(bundle.wallet.transferTransaction(
    [{ type: 'unshielded', outputs }],
    { shieldedSecretKeys: bundle.zswapSecretKeys, dustSecretKey: bundle.dustSecretKey },
    { ttl: ttlOneHour(), payFees: true },
  ), budgets.buildMs, 'build');
  // SIGN BEFORE FINALIZING. finalizeRecipe only PROVES and BINDS -- it never
  // signs. Every unshielded input needs a signature, and skipping this step got
  // the transaction rejected by the node with
  //   1010: Invalid Transaction: Custom error: 192
  // which is MalformedError::InputsSignaturesLengthMismatch (inputs != sigs).
  // Contract deploys and calls never hit this because they carry no unshielded
  // inputs, which is why the rest of the harness worked without it.
  const signed = await bundle.wallet.signRecipe(
    recipe, (data: Uint8Array) => bundle.unshieldedKeystore.signData(data),
  );
  const t1 = Date.now();
  const finalized = await withTimeout(
    bundle.wallet.finalizeRecipe(signed), budgets.proveMs, 'prove');
  const t2 = Date.now();
  const txId = await withTimeout(
    submitWithWait(bundle.wallet, finalized, wait), budgets.submitMs, 'submit');
  return { txId, buildMs: t1 - t0, proveMs: t2 - t1, submitMs: Date.now() - t2 };
}


/**
 * Unwrap an SDK error into something actionable.
 *
 * "Transaction submission error" and "Failed to prove transaction" are catch-all
 * wrappers; the real reason (node rejection text, HTTP status, WASM panic,
 * Effect _tag) is buried in a .cause/.error chain. deploy.ts learned this the
 * hard way -- same walk here so a failed submit says WHY on the first attempt
 * instead of costing another 10-minute cold sync to diagnose.
 */
function describeError(e: any): string {
  const parts: string[] = [];
  const seen = new Set<any>();

  // Effect wraps every failure from runPromise in a FiberFailure, and stashes the
  // real Cause under a well-known SYMBOL -- not under .cause. Walking only
  // .cause/.error therefore stops at the useless top-level wrapper, which is why
  // the first attempt reported nothing but "Transaction submission error".
  const effectCause = (o: any): any => {
    for (const sym of Object.getOwnPropertySymbols(o ?? {})) {
      if (String(sym).includes('Cause')) return (o as any)[sym];
    }
    return undefined;
  };

  const walk = (cur: any, depth: number, path: string) => {
    if (!cur || depth > 8 || seen.has(cur)) return;
    seen.add(cur);
    const bits: string[] = [];
    if (typeof cur === 'string') { parts.push(`${path} "${cur.slice(0, 300)}"`); return; }
    if (cur.message) bits.push(String(cur.message).slice(0, 300));
    if (cur._tag) bits.push(`_tag=${cur._tag}`);
    if (cur.name && cur.name !== 'Error') bits.push(`name=${cur.name}`);
    if (cur.status) bits.push(`status=${cur.status}`);
    if (cur.code) bits.push(`code=${cur.code}`);
    if (cur.response?.status) bits.push(`http=${cur.response.status}`);
    if (cur.body) bits.push(`body=${String(cur.body).slice(0, 300)}`);
    // Effect Cause nodes carry the payload on .error / .defect rather than .cause.
    if (typeof cur.error === 'string') bits.push(`error=${cur.error.slice(0, 300)}`);
    if (typeof cur.defect === 'string') bits.push(`defect=${cur.defect.slice(0, 300)}`);
    if (bits.length) parts.push(`${path} ${bits.join('  ')}`);
    // Anything left that is not a known key and looks informative.
    for (const k of Object.getOwnPropertyNames(cur)) {
      if (['message', 'stack', 'name', '_tag', 'cause', 'error', 'defect'].includes(k)) continue;
      const v = (cur as any)[k];
      if (typeof v === 'string' && v.length && v.length < 300) parts.push(`${path}.${k}="${v}"`);
    }
    for (const [k, v] of [['cause', cur.cause], ['error', cur.error], ['defect', cur.defect],
                          ['left', cur.left], ['right', cur.right], ['effect', effectCause(cur)]] as const) {
      if (v && typeof v === 'object') walk(v, depth + 1, `${path}.${k}`);
      else if (typeof v === 'string' && k !== 'cause') { /* already captured above */ }
    }
  };
  walk(e, 0, '[e]');
  return parts.join(' | ') || String(e);
}


/**
 * Which ledger rejections are worth retrying, and why.
 *
 * Codes come from the node's own mapping in
 * midnight-node/ledger/src/versions/common/types.rs (`From<LedgerApiError> for u8`),
 * surfaced to us as `1010: Invalid Transaction: Custom error: N`.
 *
 *   170 InvalidDustSpendProof   -- the dust spend proof was built against a dust
 *                                  merkle-tree view that the chain has already
 *                                  moved past. Purely a staleness race: observed
 *                                  on w009's split, and an immediate retry
 *                                  succeeded. This is the intermittent 5-15%
 *                                  failure that dogged every run in this harness.
 *   171 OutOfDustValidityWindow -- same family: our dust view sat outside the
 *                                  window the ledger will accept.
 *   228 IntentTtlExpired        -- the transaction took longer to build+prove
 *                                  than its TTL allowed. A rebuild gets a fresh TTL.
 *
 * Everything else is deliberately NOT retried. 192 (InputsSignaturesLengthMismatch)
 * and 138 (BalanceCheckOverspend) are deterministic construction bugs -- retrying
 * them just burns proofs and hides the defect, which is exactly how they stayed
 * unexplained for so long.
 *
 * A retry must REBUILD from scratch, not resubmit: the stale proof is baked into
 * the finalized transaction. The failed attempt reverts its coin claims (the
 * facade reverts on throw, and submitWithWait reverts explicitly), so a fresh
 * build gets clean inputs.
 */
const RETRYABLE_LEDGER_CODES = new Map<number, string>([
  [170, 'InvalidDustSpendProof'],
  [171, 'OutOfDustValidityWindow'],
  [228, 'IntentTtlExpired'],
]);

function retryableCode(detail: string): number | null {
  const m = /Custom error:\s*(\d+)/.exec(detail);
  if (!m) return null;
  const code = Number(m[1]);
  return RETRYABLE_LEDGER_CODES.has(code) ? code : null;
}

let retriedTotal = 0;

/** submitTransfer with bounded rebuild-and-retry on transient ledger rejections. */
async function submitTransferRetrying(
  bundle: any,
  outputs: { type: string; receiverAddress: any; amount: bigint }[],
  wait: SubmitWait,
  opts: { attempts: number; delayMs: number; label: string; budgets: StageBudgets },
): Promise<{ txId: string; buildMs: number; proveMs: number; submitMs: number; retries: number }> {
  let lastErr: any;
  for (let attempt = 1; attempt <= opts.attempts; attempt++) {
    try {
      const r = await submitTransfer(bundle, outputs, wait, opts.budgets);
      return { ...r, retries: attempt - 1 };
    } catch (e: any) {
      lastErr = e;
      if (e instanceof StageTimeout) throw e;   // see withTimeout: never retried
      const detail = describeError(e);
      const code = retryableCode(detail);
      if (code === null || attempt === opts.attempts) throw e;
      retriedTotal++;
      console.error(`  [${opts.label}] ${code} ${RETRYABLE_LEDGER_CODES.get(code)} ` +
        `-- rebuilding (attempt ${attempt + 1}/${opts.attempts})`);
      // Linear backoff: the dust tree needs a moment to advance and our sync to
      // catch up. Sub-second retries just reproduce the same stale view.
      await sleep(opts.delayMs * attempt);
    }
  }
  throw lastErr;
}

